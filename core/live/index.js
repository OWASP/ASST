'use strict';
/*
 * Opt-in live checks against the running site (--url / LIVE_SCAN_URL).
 *
 * Read-only by design: GET and HEAD requests only, localhost and private networks unless
 * --allow-remote, at most 60 requests at five per second, no cookies or credentials sent,
 * no forms submitted, and no response body is copied into a report.
 *
 * Probes: security headers, version banners, cookie attributes, HTTP-to-HTTPS redirect,
 * CORS origin reflection, PHP error output, directory listings, and whether the files the
 * static scan flagged (backups, dumps, .env, .git) can be downloaded.
 */
const crypto = require('crypto');
const { resolveTarget } = require('./target');
const { LiveClient } = require('./client');

const REDIRECT = new Set([301, 302, 303, 307, 308]);
const SESSION_COOKIE = /sess|^sid$|auth|token|login|remember|logged_in/i;
const LISTING = /<title>\s*Index of \/|<h1>\s*Index of \/|Directory listing for \/|<title>\s*Directory Listing/i;
const PHP_ERROR = /(?:<b>)?(Warning|Notice|Fatal error|Parse error|Deprecated|Uncaught [\w\\]+)(?:<\/b>)?:\s[^\n]{0,400}? in (?:<b>)?[^<\n]{1,300}?(?:<\/b>)? on line (?:<b>)?\d+/i;
const STACK_TRACE = /Stack trace:\s*(?:<br\s*\/?>)?\s*#0 /i;
const GENERIC_FILES = ['.env', '.git/HEAD', 'phpinfo.php', 'info.php', 'backup.sql', 'dump.sql', 'database.sql', '.DS_Store'];
const DIR_HINT = /upload|file|image|img|asset|backup|doc|download|include|inc|log|tmp|temp|data|media|static|css|js|lib|vendor|private|admin/i;
const SEVERITY_ORDER = ['info', 'low', 'medium', 'high', 'critical'];

function header(res, name) {
  const v = res && res.headers ? res.headers[name] : undefined;
  if (Array.isArray(v)) return v.join(', ');
  return v || null;
}

function isHtml(res) {
  return /html/i.test(header(res, 'content-type') || '') || /<html|<!doctype html/i.test(String(res.body || '').slice(0, 512));
}

function maxSeverity(a, b) {
  return SEVERITY_ORDER.indexOf(a) >= SEVERITY_ORDER.indexOf(b) ? a : b;
}

/** Kind of a sensitive file, used to validate the answer and to rate the exposure. */
function fileKind(rel) {
  const name = rel.split('/').pop().toLowerCase();
  if (/(^|\/)\.git(\/|$)/.test(rel)) return 'git';
  if (/^\.env/.test(name)) return 'env';
  if (/\.sql(\.gz|\.zip|\.bz2)?$/.test(name)) return 'dump';
  if (/\.(zip|tar|gz|tgz|7z|rar|bz2)$/.test(name)) return 'archive';
  if (/(\.bak|\.old|\.orig|\.save|\.swp|\.backup|~)$/.test(name)) return 'backup';
  if (/\.(pem|key|p12|pfx|ppk|jks)$|^id_(rsa|dsa|ecdsa|ed25519)$/.test(name)) return 'key';
  if (/\.log$/.test(name)) return 'log';
  if (/^(phpinfo|info|php_?info|test)\.php$/.test(name)) return 'phpinfo';
  if (/^(composer\.(json|lock)|package(-lock)?\.json|yarn\.lock|bower\.json|npm-shrinkwrap\.json)$/.test(name)) return 'manifest';
  if (name === '.ds_store') return 'dsstore';
  return 'other';
}

const KIND_SEVERITY = { git: 'critical', env: 'critical', dump: 'critical', archive: 'critical', backup: 'critical', key: 'critical', log: 'high', phpinfo: 'medium', manifest: 'low', dsstore: 'low', other: 'medium' };
const KIND_LABEL = { git: 'version-control data', env: 'environment file', dump: 'database dump', archive: 'archive', backup: 'backup copy of a source file', key: 'key file', log: 'log file', phpinfo: 'phpinfo() page', manifest: 'dependency manifest', dsstore: 'macOS folder metadata', other: 'file' };

const VALIDATE = {
  git: (b) => /^(ref: refs\/|[0-9a-f]{40}\s*$)/.test(b),
  env: (b) => /^\s*[A-Z_][A-Z0-9_]*\s*=/m.test(b),
  dump: (b, res) => /(CREATE TABLE|INSERT INTO|DROP TABLE|-- (MySQL|MariaDB) dump|PostgreSQL database dump)/i.test(b) || !isHtml(res),
  archive: (b, res) => !isHtml(res),
  backup: (b, res) => /<\?php/.test(b) || !isHtml(res),
  key: (b) => /-----BEGIN /.test(b),
  log: (b, res) => !isHtml(res),
  phpinfo: (b) => /phpinfo\(\)|<title>PHP \d|PHP Version \d/i.test(b),
  manifest: (b) => /^\s*[{[]/.test(b) || /^# (yarn lockfile|THIS IS AN AUTOGENERATED FILE)/m.test(b),
  dsstore: (b) => b.includes('Bud1'),
  other: () => true,
};

function urlFor(base, rel) {
  return new URL(rel.split('/').map(encodeURIComponent).join('/'), base).href;
}

function parseCookie(line) {
  const parts = String(line).split(';').map((s) => s.trim()).filter(Boolean);
  const [nameValue, ...attrs] = parts;
  const eq = nameValue.indexOf('=');
  const name = (eq === -1 ? nameValue : nameValue.slice(0, eq)).trim();
  const value = eq === -1 ? '' : nameValue.slice(eq + 1).trim();
  const has = (a) => attrs.some((x) => x.split('=')[0].trim().toLowerCase() === a);
  const attr = (a) => {
    const hit = attrs.find((x) => x.split('=')[0].trim().toLowerCase() === a);
    return hit && hit.includes('=') ? hit.slice(hit.indexOf('=') + 1).trim() : null;
  };
  const expires = attr('expires');
  const deleted = value === '' || value === 'deleted' || attr('max-age') === '0' || Boolean(expires && Date.parse(expires) < Date.now());
  return { name, httpOnly: has('httponly'), secure: has('secure'), sameSite: attr('samesite'), deleted };
}

function cookieHits(responses, isHttps) {
  const seen = new Set();
  const hits = [];
  for (const res of responses) {
    if (!res || !res.headers) continue;
    const raw = res.headers['set-cookie'];
    for (const line of Array.isArray(raw) ? raw : raw ? [raw] : []) {
      const c = parseCookie(line);
      if (!c.name || c.deleted || seen.has(c.name)) continue;
      seen.add(c.name);
      const missing = [];
      if (!c.httpOnly) missing.push('HttpOnly');
      if (isHttps && !c.secure) missing.push('Secure');
      if (!c.sameSite) missing.push('SameSite');
      else if (/^none$/i.test(c.sameSite) && !c.secure) missing.push('Secure (required with SameSite=None)');
      if (!missing.length) continue;
      const session = SESSION_COOKIE.test(c.name) || /^PHPSESSID$/i.test(c.name);
      hits.push({
        ruleId: 'LIVE-COOKIE-001',
        severity: session && !c.httpOnly ? 'medium' : 'low',
        url: res.url,
        message: `The ${session ? 'session ' : ''}cookie "${c.name}" set by ${res.url} has no ${missing.join(', ')} attribute${missing.length > 1 ? 's' : ''}.${!c.httpOnly ? ' Scripts injected into the page can read it.' : ''}`,
      });
    }
  }
  return hits;
}

function errorOutput(res) {
  const body = String(res && res.body ? res.body : '');
  const m = PHP_ERROR.exec(body);
  if (m) return m[1];
  if (STACK_TRACE.test(body)) return 'stack trace';
  return null;
}

/** Folders of the project that have no index page, most interesting first. */
function listingCandidates(files, limit) {
  const dirs = new Map();
  for (const f of files) {
    const parts = f.rel.split('/');
    for (let i = 1; i < parts.length && i <= 2; i++) {
      const dir = parts.slice(0, i).join('/');
      if (dir.startsWith('.')) continue;
      if (!dirs.has(dir)) dirs.set(dir, false);
    }
    if (/^(index|default)\.(php|html?|phtml)$/i.test(parts[parts.length - 1]) && parts.length > 1) dirs.set(parts.slice(0, -1).join('/'), true);
  }
  return [...dirs.entries()]
    .filter(([, hasIndex]) => !hasIndex)
    .map(([dir]) => dir)
    .sort((a, b) => (DIR_HINT.test(b) - DIR_HINT.test(a)) || (a.split('/').length - b.split('/').length) || a.localeCompare(b))
    .slice(0, limit);
}

/**
 * @param {{url:string, allowRemote?:boolean, project:{files:Array}, exposed?:string[], pages?:string[],
 *          notices:{add:Function}, log?:Function, lookup?:Function, clientOptions?:object}} p
 * @returns {Promise<{hits:Array, confirmedFiles:Array, listings:Array, info:object|null}>}
 */
async function runLiveChecks(p) {
  const empty = { hits: [], confirmedFiles: [], listings: [], info: null };
  const warn = (message) => {
    p.notices.add('warning', message);
    if (p.log) p.log(message);
  };
  const target = await resolveTarget(p.url, { allowRemote: p.allowRemote, lookup: p.lookup });
  if (!target.ok) {
    warn(`Live checks skipped: ${target.reason}`);
    return empty;
  }
  if (target.remote) {
    warn(`Live checks were run against ${target.url.host}, which is not a local address. Only test sites you own or are explicitly authorized to test.`);
  }
  const client = new LiveClient({ target, ...(p.clientOptions || {}) });
  const base = target.url;
  const isHttps = base.protocol === 'https:';
  const hits = [];
  const responses = [];
  const get = async (url, opts) => {
    const res = await client.fetch(url, opts);
    if (res && res.status) responses.push(res);
    return res;
  };

  // 1. the start page (one same-host redirect is followed, e.g. /app -> /app/)
  const first = await get(base.href);
  if (!first || !first.status) {
    warn(`Live checks skipped: ${base.href} did not answer (${(first && first.error) || 'no response'}). Start the web server (for example Apache in the XAMPP control panel) or correct --url.`);
    return { ...empty, info: { url: base.href, requests: client.log.length, methods: ['GET'] } };
  }
  let page = first;
  let redirectedToHttps = false;
  if (REDIRECT.has(first.status) && header(first, 'location')) {
    const next = new URL(header(first, 'location'), base);
    redirectedToHttps = !isHttps && next.protocol === 'https:';
    if (next.hostname === base.hostname) page = (await get(next.href)) || first;
  }

  // 2. a page that does not exist, for error pages and "soft 404" answers
  const missing = await get(new URL(`asst-check-${crypto.randomBytes(6).toString('hex')}.html`, base).href);
  const sameAsMissing = (res) => missing && missing.status === 200 && res.status === 200 && res.body === missing.body;

  // 3. security headers on the start page
  if (page.status && page.status < 400 && isHtml(page)) {
    const h = (n) => header(page, n);
    const csp = h('content-security-policy');
    const absent = [];
    if (!csp) absent.push('Content-Security-Policy');
    if (!/nosniff/i.test(h('x-content-type-options') || '')) absent.push('X-Content-Type-Options: nosniff');
    if (!h('x-frame-options') && !/frame-ancestors/i.test(csp || '')) absent.push('X-Frame-Options or CSP frame-ancestors');
    if (!h('referrer-policy')) absent.push('Referrer-Policy');
    if (page.url.startsWith('https:') && !h('strict-transport-security')) absent.push('Strict-Transport-Security');
    if (absent.length) {
      hits.push({ ruleId: 'LIVE-HDR-001', url: page.url, message: `${page.url} is served without these security headers: ${absent.join(', ')}.` });
    }
  }

  // 4. CORS: is an arbitrary Origin reflected?
  const probeOrigin = 'https://asst-cors-check.example';
  const cors = await get(page.url, { headers: { origin: probeOrigin } });
  if (cors && header(cors, 'access-control-allow-origin') === probeOrigin) {
    const credentials = /^true$/i.test(header(cors, 'access-control-allow-credentials') || '');
    hits.push({
      ruleId: 'LIVE-CORS-001',
      severity: credentials ? 'high' : 'medium',
      url: page.url,
      message: `${page.url} answers any Origin with a matching Access-Control-Allow-Origin header${credentials ? ' and Access-Control-Allow-Credentials: true, so any website can read responses with the visitor\'s cookies' : ''}. Allow only the origins you trust.`,
    });
  }

  // 5. HTTPS: available, and is plain HTTP redirected to it? (default ports only)
  let httpsAvailable = isHttps ? true : null;
  if (!base.port) {
    if (!isHttps) {
      const alt = new URL(base.href);
      alt.protocol = 'https:';
      const res = await client.fetch(alt.href, { method: 'HEAD', timeoutMs: 4000 });
      httpsAvailable = Boolean(res && res.status);
      if (httpsAvailable && !redirectedToHttps) {
        hits.push({ ruleId: 'LIVE-TLS-001', url: base.href, message: `${base.href} is answered over plain HTTP although ${alt.href} works. Redirect every HTTP request to HTTPS and add Strict-Transport-Security.` });
      } else if (!httpsAvailable) {
        p.notices.add('info', `${base.host} is served over plain HTTP only. That is normal on a development machine; the production site needs HTTPS with a redirect from HTTP and HSTS.`);
      }
    } else {
      const alt = new URL(base.href);
      alt.protocol = 'http:';
      const res = await client.fetch(alt.href, { method: 'HEAD', timeoutMs: 4000 });
      if (res && res.status >= 200 && res.status < 300) {
        hits.push({ ruleId: 'LIVE-TLS-001', url: alt.href, message: `${alt.href} answers over plain HTTP instead of redirecting to HTTPS.` });
      }
    }
  }

  // 6. files the static scan flagged, then a few well-known names
  const confirmedFiles = [];
  const wanted = [];
  for (const rel of p.exposed || []) {
    const probe = /(^|\/)\.git$/.test(rel) ? `${rel}/HEAD` : rel;
    if (!wanted.some((w) => w.probe === probe)) wanted.push({ file: rel, probe, fromScan: true });
  }
  for (const rel of GENERIC_FILES) if (!wanted.some((w) => w.probe === rel)) wanted.push({ file: null, probe: rel, fromScan: false });
  for (const w of wanted.slice(0, 28)) {
    if (client.remaining <= 8) break;
    const kind = fileKind(w.probe);
    const res = await get(urlFor(base, w.probe), { maxBytes: 16 * 1024 });
    if (!res || res.status !== 200 || sameAsMissing(res)) continue;
    if (!VALIDATE[kind](String(res.body || ''), res)) continue;
    confirmedFiles.push({ file: w.file, probe: w.probe, url: res.url, status: res.status, kind, severity: KIND_SEVERITY[kind], label: KIND_LABEL[kind], fromScan: w.fromScan });
  }

  // 7. directory listings in folders without an index page
  const listings = [];
  if (LISTING.test(String(page.body || ''))) listings.push({ dir: '', url: page.url });
  for (const dir of listingCandidates(p.project.files || [], 8)) {
    if (client.remaining <= 4) break;
    const res = await get(urlFor(base, `${dir}/`), { maxBytes: 32 * 1024 });
    if (res && res.status === 200 && LISTING.test(String(res.body || ''))) listings.push({ dir, url: res.url });
  }

  // 8. pages that start sessions (login pages): cookie attributes
  for (const rel of (p.pages || []).slice(0, 2)) {
    if (client.remaining <= 2) break;
    await get(urlFor(base, rel), { maxBytes: 64 * 1024 });
  }

  // findings from everything that was fetched
  hits.push(...cookieHits(responses, isHttps));
  const leaks = new Map();
  let php = null;
  for (const res of responses) {
    for (const name of ['server', 'x-powered-by', 'x-aspnet-version', 'x-generator']) {
      const v = header(res, name);
      if (v && /\d+\.\d+/.test(v) && !leaks.has(name)) leaks.set(name, v);
      const m = v && /PHP\/(\d+\.\d+(?:\.\d+)?)/i.exec(v);
      if (m && !php) php = m[1];
    }
    const sig = /<address>([^<]*\d+\.\d+[^<]*)<\/address>/i.exec(String(res.body || ''));
    if (sig && !leaks.has('error page')) leaks.set('error page', sig[1].replace(/\s+/g, ' ').trim());
  }
  if (leaks.size) {
    const list = [...leaks.entries()].map(([k, v]) => `${k === 'error page' ? 'error page signature' : k.replace(/(^|-)\w/g, (s) => s.toUpperCase())}: ${v}`);
    hits.push({ ruleId: 'LIVE-INFO-001', url: page.url, message: `Software versions are announced to every visitor (${list.join('; ')}). Hide them, for example with ServerTokens Prod, ServerSignature Off and expose_php = Off.` });
  }
  const errorPages = responses.filter((r) => errorOutput(r));
  if (errorPages.length) {
    // the "not found" probe has a random name; describe it instead of quoting it, so the finding stays stable
    const first = errorPages.find((r) => !missing || r.url !== missing.url) || errorPages[0];
    const where = missing && first.url === missing.url ? `The "not found" page of ${base.href}` : first.url;
    hits.push({ ruleId: 'LIVE-ERR-001', url: missing && first.url === missing.url ? base.href : first.url, message: `${where} shows a PHP ${errorOutput(first)} message with file paths${errorPages.length > 1 ? ` (${errorPages.length} pages in total)` : ''}. Turn display_errors off on the server and log errors instead.` });
  }

  const methods = [...new Set(client.log.map((e) => e.method))];
  return {
    hits,
    confirmedFiles,
    listings,
    info: {
      url: base.href,
      server: header(page, 'server'),
      poweredBy: header(page, 'x-powered-by'),
      php,
      https: httpsAvailable,
      requests: client.log.length,
      methods,
    },
  };
}

module.exports = { runLiveChecks, fileKind, parseCookie, listingCandidates, maxSeverity, KIND_SEVERITY };
